// Joins css/*.css into styles.css and embeds Fraunces (SIL OFL) so the look works without installing a font.
import { readFileSync, writeFileSync } from "fs";

const font = (file, style) => `@font-face {
	font-family: "Event Horizon Fraunces";
	font-style: ${style};
	font-weight: 100 900;
	font-display: swap;
	src: url(data:font/woff2;base64,${readFileSync(`fonts/${file}`).toString("base64")}) format("woff2");
	unicode-range: U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC, U+0304, U+0308, U+0329, U+2000-206F, U+20AC, U+2122, U+2191, U+2193, U+2212, U+2215, U+FEFF, U+FFFD;
}`;

const parts = ["look", "rewards", "typewriter", "stats", "reading"].map((n) => readFileSync(`css/${n}.css`, "utf8"));
const out = [
	"/* Event Horizon — generated by scripts/build-css.mjs from css/. Edit those files, not this one. */",
	"/* Fraunces by Undercase Type, SIL Open Font License 1.1 (see fonts/OFL.txt). */",
	font("Fraunces-latin.woff2", "normal"),
	font("Fraunces-Italic-latin.woff2", "italic"),
	...parts,
].join("\n\n");
writeFileSync("styles.css", out);
console.log(`styles.css: ${(out.length / 1024).toFixed(0)} KB`);
