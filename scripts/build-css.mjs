// Joins css/*.css into styles.css (Obsidian loads one stylesheet per plugin).
import { readFileSync, writeFileSync } from "fs";

const parts = ["look", "rewards", "typewriter", "stats", "reading", "newtab"].map((n) => readFileSync(`css/${n}.css`, "utf8"));
const out = ["/* Event Horizon — generated by scripts/build-css.mjs from css/. Edit those files, not this one. */", ...parts].join("\n\n");
writeFileSync("styles.css", out);
console.log(`styles.css: ${(out.length / 1024).toFixed(0)} KB`);
